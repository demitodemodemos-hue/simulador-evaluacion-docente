-- -------------------------------------------------------------
-- LOGIN ATÓMICO
-- Si existe una sesión con actividad en los últimos 3 minutos,
-- otro dispositivo no puede entrar con el mismo usuario.
-- -------------------------------------------------------------
create or replace function public.login_participante(
  p_nombre text,
  p_correo text,
  p_session_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_user public.participantes%rowtype;
begin
  select * into v_user
  from public.participantes
  where activo = true
    and extensions.unaccent(lower(trim(regexp_replace(nombre, '\\s+', ' ', 'g')))) =
        extensions.unaccent(lower(trim(regexp_replace(p_nombre, '\\s+', ' ', 'g'))))
    and lower(trim(correo)) = lower(trim(p_correo))
  for update;

  if not found then
    return jsonb_build_object('ok', false, 'code', 'INVALID');
  end if;

  if v_user.session_token is not null
     and v_user.session_token <> p_session_token
     and v_user.session_last_seen is not null
     and v_user.session_last_seen > now() - interval '3 minutes' then
    return jsonb_build_object('ok', false, 'code', 'BUSY');
  end if;

  update public.participantes
     set session_token = p_session_token,
         session_last_seen = now()
   where id = v_user.id;

  return jsonb_build_object(
    'ok', true,
    'code', 'OK',
    'user', jsonb_build_object(
      'id', v_user.id,
      'nombre', v_user.nombre,
      'correo', v_user.correo
    )
  );
end;
$$;

-- Mantiene viva la sesión. Devuelve false si la sesión ya no pertenece
-- a este dispositivo o fue reemplazada/expiró.
create or replace function public.heartbeat_participante(p_session_token uuid)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_updated integer;
begin
  update public.participantes
     set session_last_seen = now()
   where activo = true
     and session_token = p_session_token;
  get diagnostics v_updated = row_count;
  return v_updated = 1;
end;
$$;

-- Cierre de sesión inmediato.
create or replace function public.logout_participante(p_session_token uuid)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_updated integer;
begin
  update public.participantes
     set session_token = null,
         session_last_seen = null
   where session_token = p_session_token;
  get diagnostics v_updated = row_count;
  return v_updated = 1;
end;
$$;

-- Guarda el resultado centralmente en Supabase.
create or replace function public.guardar_resultado(
  p_session_token uuid,
  p_modalidad text,
  p_correctas integer,
  p_incorrectas integer,
  p_sin_responder integer,
  p_total integer,
  p_porcentaje numeric,
  p_tiempo_segundos integer,
  p_escala integer,
  p_envio_automatico boolean
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_participante_id bigint;
begin
  select id into v_participante_id
  from public.participantes
  where activo = true
    and session_token = p_session_token
    and session_last_seen > now() - interval '5 minutes';

  if v_participante_id is null then
    return false;
  end if;

  insert into public.resultados(
    participante_id, modalidad, correctas, incorrectas, sin_responder,
    total, porcentaje, tiempo_segundos, escala, envio_automatico
  ) values (
    v_participante_id, p_modalidad, p_correctas, p_incorrectas, p_sin_responder,
    p_total, p_porcentaje, p_tiempo_segundos, p_escala, p_envio_automatico
  );

  update public.participantes
     set session_last_seen = now()
   where id = v_participante_id;

  return true;
end;
$$;

