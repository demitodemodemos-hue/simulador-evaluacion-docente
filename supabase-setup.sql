create extension if not exists unaccent with schema extensions;

create table if not exists public.participantes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  correo text not null,
  activo boolean not null default true,
  session_token uuid,
  session_last_seen timestamptz,
  created_at timestamptz not null default now()
);

create unique index if not exists participantes_correo_unique
  on public.participantes (lower(trim(correo)));

create table if not exists public.resultados (
  id bigint generated by default as identity primary key,
  participante_id bigint not null references public.participantes(id) on delete cascade,
  fecha timestamptz not null default now(),
  modalidad text not null,
  correctas integer not null,
  incorrectas integer not null,
  sin_responder integer not null,
  total integer not null,
  porcentaje numeric(5,2) not null,
  tiempo_segundos integer not null,
  escala integer,
  envio_automatico boolean not null default false
);

-- Las tablas NO se exponen directamente al navegador.
alter table public.participantes enable row level security;
alter table public.resultados enable row level security;
revoke all on table public.participantes from anon, authenticated;
